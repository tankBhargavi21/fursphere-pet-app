export const ensureAdminUser = async () => {
  try {
    const bcrypt = (await import('bcryptjs')).default;
    const User = (await import('../models/User.js')).default;
    const { getDBStatus } = await import('../config/db.js');
    const { LocalStore } = await import('./storage.js');
    const { isConnected } = getDBStatus();

    const adminEmails = ['pixelpilot03@gmail.com', 'admin@fursphere.com'];
    const defaultPassword = 'admin123';
    const hashedPassword = await bcrypt.hash(defaultPassword, 10);

    for (const email of adminEmails) {
      if (isConnected) {
        let admin = await User.findOne({ email });
        if (!admin) {
          console.log(`[FurSphere Auth] Creating administrator account (${email})...`);
          await User.create({
            name: email === 'pixelpilot03@gmail.com' ? 'PixelPilot Admin' : 'FurSphere Admin',
            email,
            phone: '9999999999',
            password: hashedPassword,
            role: 'admin',
            addresses: [{
              title: 'FurSphere HQ',
              street: 'FurSphere House, Ring Road',
              city: 'Ahmedabad',
              state: 'Gujarat',
              pincode: '380015',
              isDefault: true
            }]
          });
          console.log(`[FurSphere Auth] Administrator ready: ${email} / ${defaultPassword}`);
        } else {
          let updated = false;
          if (admin.role !== 'admin') {
            admin.role = 'admin';
            updated = true;
          }
          if (admin.password !== hashedPassword) {
            admin.password = hashedPassword;
            updated = true;
          }
          if (updated) {
            await admin.save();
            console.log(`[FurSphere Auth] Verified and updated ${email} credentials!`);
          }
        }
      } else {
        let users = LocalStore.get('users') || [];
        let admin = users.find((u) => u.email === email);
        if (!admin) {
          admin = {
            _id: 'user_admin_' + Date.now(),
            name: email === 'pixelpilot03@gmail.com' ? 'PixelPilot Admin' : 'FurSphere Admin',
            email,
            phone: '9999999999',
            password: hashedPassword,
            role: 'admin',
            addresses: [],
            createdAt: new Date().toISOString()
          };
          users.push(admin);
          LocalStore.set('users', users);
        } else {
          admin.role = 'admin';
          LocalStore.set('users', users);
        }
      }
    }
  } catch (err) {
    console.error('[FurSphere Auth] Error ensuring admin user:', err.message);
  }
};
